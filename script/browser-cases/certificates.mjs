import assert from 'node:assert/strict'
import { X509Certificate, createPrivateKey } from 'node:crypto'
import JSZip from 'jszip'

async function bytes(download) {
  const stream = await download.createReadStream()
  assert.ok(stream)
  const chunks = []
  for await (const chunk of stream) chunks.push(chunk)
  return Buffer.concat(chunks)
}
const route = '/tools/nginx-certificate-generator'
export async function run(page, check) {
  const fill = (id, value) => page.getByTestId(id).fill(value)
  const click = id => page.getByTestId(id).click()
  const output = id => page.getByTestId(id).getByTestId('tool-output').inputValue()
  const prepare = async () => {
    await page.goto(route)
    await fill('cert-email', 'admin@example.com')
    await page.getByTestId('cert-terms').check()
  }
  await check('certificates/public: Nginx issuance, copy, configuration download and renewal', async () => {
    await prepare()
    await fill('cert-domains', 'EXAMPLE.COM www.example.com')
    await fill('cert-port', '3000')
    await click('cert-generate')
    await page.getByTestId('cert-public-result').waitFor()
    assert.match(await output('cert-issue-output'), /sudo certbot --nginx --redirect/)
    assert.match(await output('cert-issue-output'), /-d 'example.com'/)
    assert.match(await output('cert-issue-output'), /acme-v02.api.letsencrypt.org/)
    await page.getByTestId('cert-issue-output').getByRole('button', { name: 'Copy', exact: true }).click()
    assert.match(await page.evaluate(() => navigator.clipboard.readText()), /--email 'admin@example.com'/)
    assert.match(await output('cert-renew-output'), /renew --dry-run/)
    const [download] = await Promise.all([page.waitForEvent('download'), page.getByTestId('cert-nginx-output').getByRole('button', { name: 'Download', exact: true }).click()])
    assert.equal(download.suggestedFilename(), 'nginx.conf')
    const config = (await bytes(download)).toString()
    assert.match(config, /proxy_pass http:\/\/127.0.0.1:3000/)
    assert.match(config, /ssl_certificate \/etc\/letsencrypt\/live\/example.com\/fullchain.pem/)
    assert.match(config, /listen \[::\]:443 ssl;/)
    await click('cert-clear')
    assert.equal(await page.getByTestId('cert-public-result').count(), 0)
  })
  await check('certificates/challenges: Webroot, wildcard DNS and staging replacement', async () => {
    await prepare()
    await page.getByTestId('cert-challenge').selectOption('webroot')
    await fill('cert-webroot', '/var/www/acme')
    await click('cert-generate')
    assert.match(await output('cert-issue-output'), /--webroot -w '\/var\/www\/acme'/)
    assert.match(await output('cert-challenge-output'), /location \^~ \/.well-known\/acme-challenge\//)
    assert.match(await output('cert-nginx-output'), /root \/var\/www\/acme;/)
    await fill('cert-domains', '*.example.com example.com')
    await click('cert-generate')
    await page.getByRole('alert').waitFor()
    assert.match(await page.getByRole('alert').innerText(), /DNS validation/)
    await page.getByTestId('cert-challenge').selectOption('cloudflare')
    await page.getByTestId('cert-staging').check()
    await click('cert-generate')
    assert.match(await output('cert-issue-output'), /-d '\*.example.com'/)
    assert.match(await output('cert-issue-output'), /acme-staging-v02/)
    assert.match(await output('cert-challenge-output'), /chmod 600/)
    assert.match(await output('cert-production-output'), /--force-renewal/)
    assert.doesNotMatch(await output('cert-production-output'), /acme-staging/)
    assert.match(await output('cert-nginx-output'), /live\/wildcard-example.com\//)
    await fill('cert-credentials', '/etc/a;touch')
    await click('cert-generate')
    await page.getByRole('alert').waitFor()
    assert.equal(await page.getByTestId('cert-public-result').count(), 0)
  })
  await check('certificates/validation: missing agreement and unsafe input never produce commands', async () => {
    await page.goto(route)
    await fill('cert-email', 'admin@example.com')
    await click('cert-generate')
    await page.getByRole('alert').waitFor()
    assert.match(await page.getByRole('alert').innerText(), /Subscriber Agreement/)
    await page.getByTestId('cert-terms').check()
    await fill('cert-domains', 'example.com;reboot')
    await click('cert-generate')
    assert.equal(await page.getByTestId('cert-public-result').count(), 0)
    assert.match(await page.getByRole('alert').innerText(), /valid DNS names/)
    await click('cert-local-mode')
    await fill('cert-domains', 'localhost')
    await fill('cert-days', '366')
    await click('cert-generate')
    await page.getByRole('alert').waitFor()
    assert.match(await page.getByRole('alert').innerText(), /1 to 365/)
  })
  for (const algorithm of ['ecdsa', 'rsa']) {
    await check(`certificates/local: real ${algorithm} generation and verified PEM/ZIP downloads`, async () => {
      await page.goto(route)
      await click('cert-local-mode')
      await fill('cert-domains', 'localhost example.test *.example.test')
      await fill('cert-days', '7')
      await page.getByTestId('cert-algorithm').selectOption(algorithm)
      await click('cert-generate')
      await page.getByTestId('cert-local-result').waitFor({ timeout: 20000 })
      assert.match(await page.getByTestId('cert-notice').innerText(), /not trust them by default/)
      const [download] = await Promise.all([page.waitForEvent('download'), click('cert-download-bundle')])
      assert.equal(download.suggestedFilename(), 'nginx-certificate.zip')
      const zip = await JSZip.loadAsync(await bytes(download))
      assert.deepEqual(Object.keys(zip.files).sort(), ['fullchain.pem', 'nginx.conf', 'privkey.pem'])
      const pem = await zip.file('fullchain.pem').async('string')
      const privatePem = await zip.file('privkey.pem').async('string')
      const cert = new X509Certificate(pem)
      const key = createPrivateKey(privatePem)
      assert.equal(cert.verify(cert.publicKey), true)
      assert.equal(cert.checkPrivateKey(key), true)
      assert.equal(cert.ca, false)
      assert.ok(cert.checkHost('sub.example.test'))
      assert.equal(cert.fingerprint256, await page.getByTestId('cert-fingerprint').innerText())
      assert.equal(key.asymmetricKeyType, algorithm === 'rsa' ? 'rsa' : 'ec')
      assert.equal(zip.file('privkey.pem').unixPermissions, 0o600)
      assert.doesNotMatch(await page.locator('main main').innerText(), /BEGIN PRIVATE KEY/)
      for (const [id, expectedName, expectedValue] of [['cert-download-cert', 'fullchain.pem', pem], ['cert-download-key', 'privkey.pem', privatePem]]) {
        const [file] = await Promise.all([page.waitForEvent('download'), click(id)])
        assert.equal(file.suggestedFilename(), expectedName)
        assert.equal((await bytes(file)).toString(), expectedValue)
      }
      const saved = await page.evaluate(() => JSON.stringify({ ...localStorage }))
      assert.ok(!saved.includes('BEGIN PRIVATE KEY'))
      await fill('cert-days', '8')
      assert.equal(await page.getByTestId('cert-local-result').count(), 0)
      await page.reload()
      assert.equal(await page.getByTestId('cert-local-result').count(), 0)
    })
  }
  await check('certificates/locales: all 12 languages run issuance controls and support mobile RTL', async () => {
    for (const locale of ['en', 'zh', 'es', 'de', 'fr', 'it', 'pt', 'ru', 'ja', 'ko', 'ar', 'hi']) {
      await page.goto(`${locale === 'en' ? '' : `/${locale}`}${route}`)
      await page.getByTestId('cert-domains').waitFor()
      await fill('cert-email', 'admin@example.com')
      await page.getByTestId('cert-terms').check()
      await click('cert-generate')
      await page.getByTestId('cert-public-result').waitFor()
      assert.match(await output('cert-issue-output'), /--cert-name 'example.com'/)
      assert.doesNotMatch(await page.locator('main main').innerText(), /tools\.nginx-certificate-generator\.|errorDomains|generatePublic/)
      assert.equal(await page.locator('html').getAttribute('lang'), locale)
    }
    await page.setViewportSize({ width: 390, height: 844 })
    await page.goto(`/ar${route}`)
    await page.getByTestId('cert-domains').waitFor()
    assert.equal(await page.locator('html').getAttribute('dir'), 'rtl')
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 2), true)
    await page.setViewportSize({ width: 1280, height: 900 })
  })
}
